def main():
    data = snapshot(load_contexts())
    main_page = ROOT / "public" / "espaluz.html"
    src = main_page.read_text(encoding="utf-8")
    style, gtag = page_shell(src)
    for c in data:
        (ROOT / "public" / f"espaluz-{c['slug']}.html").write_text(build_page(c, data, style, gtag), encoding="utf-8")
    links = "\n".join(
        f"        <a class=\"country\" href=\"/espaluz/{c['slug']}\">{c['flag']} {esc(title_name(c))}</a>" for c in data)
    block = f"<!-- countries:start (scripts/build-espaluz-countries.py) -->\n      <nav class=\"countries\" aria-label=\"Countries\">\n{links}\n      </nav>\n      <!-- countries:end -->"
    new_src, n = re.subn(r"<!-- countries:start.*?<!-- countries:end -->", block, src, flags=re.S)
    if n != 1:
        sys.exit("public/espaluz.html has no countries:start/end markers")
    main_page.write_text(new_src, encoding="utf-8")
    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / "espaluz-countries.json").write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"built {len(data)} country pages from {SRC.name}")


if __name__ == "__main__":
    main()
