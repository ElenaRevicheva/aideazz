#!/usr/bin/env python3
"""Build aideazz.xyz/espaluz/<country> — one page per Spanish-speaking country (Elena, 2 Nov 2026:
"live your new country in Spanish").

Every word on these pages comes from the bots' own country data, EspaLuzWhatsApp
`espaluz_country_contexts_full.py` (the same file powers WhatsApp and Telegram). Nothing is generated by a model,
so there is nothing to hallucinate.

Only the evergreen layer is published: local expressions and their meanings, food words, customs, the bilingual
phrases for real situations, and which everyday topics EspaLuz has a guide for. Left out on purpose: addresses,
emergency numbers, hospital/school names, prices, visa rules and rates (they go out of date), vulgar or ethnic
slang, and notes that generalise about a people. Those stay inside the bots, where they can be corrected.

    python scripts/build-espaluz-countries.py [path/to/espaluz_country_contexts_full.py]

Writes public/espaluz-<slug>.html (FLAT files — never a public/espaluz/ directory, IPFS would 301), the country
list inside public/espaluz.html between the countries markers, and data/espaluz-countries.json (the snapshot).
"""
